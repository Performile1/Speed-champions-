// Helper: Convert preset SVG to data URL for Three.js texture
export function getPresetSponsorDataUrl(preset: PresetSponsorLogo): string {
  const cleanSvg = preset.svgIcon.replace(/class="[^"]*"/, 'xmlns="http://www.w3.org/2000/svg"');
  return `data:image/svg+xml;utf8,${encodeURIComponent(cleanSvg)}`;
}

